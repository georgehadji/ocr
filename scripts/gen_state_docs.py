"""Render the declared state machines into docs/STATE_MACHINES.md.

``python scripts/gen_state_docs.py`` rewrites the file; ``--check`` exits 1 when
the committed file differs from what the code declares, so the catalog an agent
or a new developer reads cannot drift from the transition tables.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

from omniocr.composition.state_machines import ALL_MACHINES
from omniocr.domain.state import MachineSpec

OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "STATE_MACHINES.md"

_HEADER = """# State machines

Generated by `scripts/gen_state_docs.py` from the transition tables in code.
Do not edit by hand: change the table, then re-run the script. CI runs it with
`--check`. Design and rollout: [STATE_MACHINES_PLAN.md](STATE_MACHINES_PLAN.md).
"""


def _render_one(spec: MachineSpec) -> str:
    lines = [
        f"## {spec.name}",
        "",
        f"Owner: `{spec.owner}`. Initial: `{spec.initial}`. "
        f"Terminal: {', '.join(f'`{s}`' for s in spec.terminal) or 'none'}.",
    ]
    if spec.external:
        lines.append(
            "Entered from outside the machine: "
            + ", ".join(f"`{s}`" for s in sorted(spec.external))
        )
    lines += ["", "```mermaid", "stateDiagram-v2", f"    [*] --> {spec.initial}"]
    for state in spec.states:
        lines += [f"    {state} --> {target}" for target in sorted(spec.transitions[state])]
    lines += ["```", "", "| State | May move to |", "|---|---|"]
    for state in spec.states:
        targets = ", ".join(f"`{t}`" for t in sorted(spec.transitions[state])) or "(terminal)"
        lines.append(f"| `{state}` | {targets} |")
    return "\n".join(lines) + "\n"


def render(machines: Sequence[MachineSpec]) -> str:
    if not machines:
        return _HEADER + "\nNo machines are registered yet.\n"
    return _HEADER + "\n" + "\n".join(_render_one(spec) for spec in machines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args(argv)

    expected = render(ALL_MACHINES)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current.replace("\r\n", "\n") != expected:
            print(
                f"{OUTPUT.name} is out of date. Run: python scripts/gen_state_docs.py",
                file=sys.stderr,
            )
            return 1
        print(f"State machine catalog is current ({len(ALL_MACHINES)} machines)")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.name} ({len(ALL_MACHINES)} machines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
